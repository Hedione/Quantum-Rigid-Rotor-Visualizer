  await expect.poll(async () => (await surface.screenshot()).equals(before)).toBe(false)
  await page.getByRole('button', { name: 'Carbon monoxide', exact: true }).click()
  for (const kind of ['classical', 'ensemble', 'wavefunction']) await expect(page.getByTestId(`scene-${kind}`)).toHaveAttribute('data-bond-length', '1.13')
  await expect(page.getByRole('spinbutton', { name: 'Particle 1 mass exact value' })).toHaveValue('12')
