import { expect, test } from '@playwright/test'
import { setRotorCount } from './controls'

declare global { interface Window { appearancePreparations: number } }

test('occlusion remembers both appearance profiles and keeps opacity editable', async ({ page }) => {
  test.setTimeout(120000)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  await page.goto('/')
  await expect(page.locator('[aria-busy]')).toHaveAttribute('aria-busy', 'false')
  await page.getByRole('button', { name: 'Pause sampling', exact: true }).click()
  const count = page.getByRole('slider', { name: 'Number of Classical Rotors', exact: true })
  const frequency = page.getByRole('slider', { name: 'Sampling frequency', exact: true })
  const radius = page.getByRole('slider', { name: 'Atom radius (visualization only)', exact: true })
  const opacity = page.getByRole('slider', { name: 'Rotor opacity', exact: true })
  const occlusion = page.getByRole('button', { name: 'Particle occlusion', exact: true })
  const canvas = page.getByTestId('scene-ensemble').locator('canvas')
  await setRotorCount(page, 80)
  await frequency.focus(); await frequency.press('Home')
  await radius.focus(); await radius.press('End')
  await opacity.focus(); await opacity.press('End')
  await occlusion.click()
  await expect(count).toHaveAttribute('aria-valuenow', '5000')
  await expect(frequency).toHaveValue('45')
  await expect(radius).toHaveValue('1')
  await expect(opacity).toBeEnabled()
  await expect(opacity).toHaveAttribute('aria-valuetext', '100%')
  await setRotorCount(page, 100)
  await radius.focus(); await radius.press('End')
  await frequency.focus(); await frequency.press('End')
  const opaque = await canvas.screenshot()
  await opacity.focus(); await opacity.press('Home')
  await expect(opacity).toHaveAttribute('aria-valuetext', '0.5%')
  await expect.poll(async () => (await canvas.screenshot()).equals(opaque)).toBe(false)
  for (let i = 0; i < 3; i++) {
    await occlusion.click()
    await expect(count).toHaveAttribute('aria-valuenow', '80'); await expect(frequency).toHaveValue('1')
    await expect(radius).toHaveValue('10'); await expect(opacity).toHaveAttribute('aria-valuetext', '75%')
    await occlusion.click()
    await expect(count).toHaveAttribute('aria-valuenow', '100'); await expect(frequency).toHaveValue('60')
    await expect(radius).toHaveValue('10'); await expect(opacity).toHaveAttribute('aria-valuetext', '0.5%')
  }
  await page.getByRole('button', { name: 'RESET SIMULATION', exact: true }).click()
  await expect(occlusion).toHaveAttribute('aria-pressed', 'false')
  await expect(count).toHaveAttribute('aria-valuenow', '5000'); await expect(frequency).toHaveValue('30')
  await expect(radius).toHaveValue('5'); await expect(opacity).toHaveAttribute('aria-valuetext', '1%')
  await occlusion.click()
  await expect(count).toHaveAttribute('aria-valuenow', '5000'); await expect(frequency).toHaveValue('45')
  await expect(radius).toHaveValue('1'); await expect(opacity).toHaveAttribute('aria-valuetext', '100%')
  expect(await canvas.evaluate(canvas => (canvas as HTMLCanvasElement).getContext('webgl2')!.getError())).toBe(0)
  expect(errors).toEqual([])
})

test('custom RGB colors update paused particles without changing samples and the popup fits narrow screens', async ({ page }) => {
  test.setTimeout(150000)
  await page.addInitScript(() => {
    window.appearancePreparations = 0
    const NativeWorker = window.Worker
    window.Worker = class extends NativeWorker {
      postMessage(message: unknown) { window.appearancePreparations++; super.postMessage(message) }
    }
  })
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  await page.goto('/')
  await expect(page.locator('[aria-busy]')).toHaveAttribute('aria-busy', 'false')
  await page.getByRole('button', { name: 'Pause sampling', exact: true }).click()
  await setRotorCount(page, 100)
  const opacity = page.getByRole('slider', { name: 'Rotor opacity', exact: true })
  await opacity.focus(); await opacity.press('End')
  const total = await page.getByTestId('cumulative-samples').innerText()
  const preparations = await page.evaluate(() => window.appearancePreparations)
  const canvas = page.getByTestId('scene-ensemble').locator('canvas')
  const before = await canvas.screenshot()
  const custom = page.getByRole('button', { name: 'Custom rotor colors', exact: true })
  const dialog = page.getByRole('dialog', { name: 'Custom rotor colors', exact: true })
  await custom.click()
  await expect(dialog).toBeVisible()
  await expect(custom).toHaveAttribute('aria-expanded', 'true')
  await expect(custom).toHaveAttribute('aria-pressed', 'true')
  for (const [channel, value] of [['Red', '255'], ['Green', '0'], ['Blue', '0']]) await dialog.getByRole('spinbutton', { name: channel, exact: true }).fill(value)
  await expect(dialog.getByLabel('Selected color', { exact: true })).toHaveText('#FF0000')
  await dialog.getByRole('button', { name: 'Particle 2', exact: true }).click()
  for (const [channel, value] of [['Red', '0'], ['Green', '0'], ['Blue', '255']]) await dialog.getByRole('spinbutton', { name: channel, exact: true }).fill(value)
  await expect(dialog.getByLabel('Selected color', { exact: true })).toHaveText('#0000FF')
  await page.keyboard.press('Escape')
  await expect(dialog).toBeHidden()
  await expect(custom).toBeFocused()
  await expect(custom).toHaveAttribute('aria-expanded', 'false')
  await expect.poll(async () => (await canvas.screenshot()).equals(before)).toBe(false)
  await page.getByRole('button', { name: 'Single mint', exact: true }).click()
  await custom.click()
  await expect(dialog.getByLabel('Selected color', { exact: true })).toHaveText('#FF0000')
  const wheel = dialog.getByRole('slider', { name: 'Color wheel', exact: true })
  await wheel.focus(); await wheel.press('Shift+ArrowRight')
  await expect(wheel).toHaveAttribute('aria-valuenow', '10')
  await wheel.click({ position: { x: 87, y: 173 } })
  await expect(wheel).toHaveAttribute('aria-valuenow', '90')
  const brightness = dialog.getByRole('slider', { name: 'Color brightness', exact: true })
  await brightness.focus(); await brightness.press('Home')
  await expect(dialog.getByLabel('Selected color', { exact: true })).toHaveText('#000000')
  await brightness.press('End')
  await expect(dialog.getByLabel('Selected color', { exact: true })).not.toHaveText('#000000')
  await dialog.getByRole('button', { name: 'Close custom colors', exact: true }).click()
  for (const width of [1440, 1101, 760, 390, 320]) {
    await page.setViewportSize({ width, height: 844 })
    await custom.click()
    if (width === 1440) {
      await page.setViewportSize({ width: 320, height: 600 })
      const resized = (await dialog.boundingBox())!
      expect(resized.x).toBeGreaterThanOrEqual(0); expect(resized.x + resized.width).toBeLessThanOrEqual(320)
      expect(resized.y).toBeGreaterThanOrEqual(0); expect(resized.y + resized.height).toBeLessThanOrEqual(600)
      await page.setViewportSize({ width, height: 844 })
    }
    const bounds = (await dialog.boundingBox())!
    expect(bounds.x).toBeGreaterThanOrEqual(0); expect(bounds.x + bounds.width).toBeLessThanOrEqual(width)
    expect(bounds.y).toBeGreaterThanOrEqual(0); expect(bounds.y + bounds.height).toBeLessThanOrEqual(844)
    expect(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
    if (width === 320) await dialog.screenshot({ path: 'test-results/custom-rotor-colors-mobile.png' })
    await page.mouse.click(2, 2)
    await expect(dialog).toBeHidden()
    await expect(custom).toHaveAttribute('aria-expanded', 'false')
  }
  await expect(page.getByTestId('cumulative-samples')).toHaveText(total)
  expect(await page.evaluate(() => window.appearancePreparations)).toBe(preparations)
  expect(await canvas.evaluate(canvas => (canvas as HTMLCanvasElement).getContext('webgl2')!.getError())).toBe(0)
  expect(errors).toEqual([])
})
