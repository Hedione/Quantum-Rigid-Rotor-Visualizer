import { expect, test } from '@playwright/test'

test('the default energy ladder shows J=0–3 with gaps proportional to the actual energy differences', async ({ page }) => {
  await page.goto('/')
  const stage = page.getByRole('region', { name: 'Unified classical and quantum rotor experiment' })
  await expect(stage).toHaveAttribute('aria-busy', 'false')
  await page.getByRole('button', { name: 'Pause sampling', exact: true }).click()
  const ladder = page.getByRole('region', { name: 'Quantized energy ladder', exact: true })
  await expect(ladder.locator('.ladder > div > span')).toHaveText(['J = 3', 'J = 2', 'J = 1', 'J = 0'])
  await expect(ladder.locator('.ladder > div > small')).toHaveText(['12 B', '6 B', '2 B', '0 B'])
  await expect(ladder.getByLabel('Energy scale break')).toHaveCount(0)
  const centers: number[] = []
  for (const j of [0, 1, 2, 3]) {
    const line = await ladder.locator(`[data-j="${j}"] > i`).boundingBox()
    centers.push(line!.y + line!.height / 2)
  }
  const firstGap = centers[0] - centers[1]
  expect(firstGap).toBeGreaterThan(20)
  expect((centers[1] - centers[2]) / firstGap).toBeCloseTo(2, 6)
  expect((centers[2] - centers[3]) / firstGap).toBeCloseTo(3, 6)
  await page.locator('.diagnostics').screenshot({ path: 'test-results/distribution-controls-desktop.png' })
  await page.locator('.physics-panel').screenshot({ path: 'test-results/energy-ladder-default.png' })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await expect(ladder).toBeVisible()
  await page.locator('.diagnostics').screenshot({ path: 'test-results/distribution-controls-mobile.png' })
  await page.locator('.physics-panel').screenshot({ path: 'test-results/observables-mobile.png' })
})

test('high occupied energies have explicit scale breaks, with degenerate J states sharing one level', async ({ page }) => {
  await page.goto('/')
  const stage = page.getByRole('region', { name: 'Unified classical and quantum rotor experiment' })
  await expect(stage).toHaveAttribute('aria-busy', 'false', { timeout: 15000 })
  await page.getByRole('button', { name: 'Pause sampling', exact: true }).click()
  const ladder = page.getByRole('region', { name: 'Quantized energy ladder', exact: true })
  const primary = page.getByRole('spinbutton', { name: 'J', exact: true })
  await primary.fill('8'); await primary.press('Enter')
  await expect(stage).toHaveAttribute('data-displayed-j', '8')
  await expect(ladder.locator('.ladder > div > span')).toHaveText(['J = 8', 'J = 3', 'J = 2', 'J = 1', 'J = 0'])
  await expect(ladder.getByLabel('Energy scale break')).toHaveCount(1)
  await page.getByRole('button', { name: 'Superposition mode', exact: true }).click()
  const secondary = page.getByRole('spinbutton', { name: 'Second J', exact: true })
  await secondary.fill('6'); await secondary.press('Enter')
  await expect(stage).toHaveAttribute('data-displayed-j2', '6')
  await expect(ladder.locator('.ladder > div > span')).toHaveText(['J = 8', 'J = 6', 'J = 3', 'J = 2', 'J = 1', 'J = 0'])
  await expect(ladder.locator('.ladder > div.current > small')).toHaveText(['72 B', '42 B'])
  const breaks = ladder.getByLabel('Energy scale break')
  await expect(breaks).toHaveCount(2)
  const top = await ladder.locator('[data-j="8"]').boundingBox()
  const middle = await ladder.locator('[data-j="6"]').boundingBox()
  const low = await ladder.locator('[data-j="3"]').boundingBox()
  const firstBreak = await breaks.nth(0).boundingBox()
  const secondBreak = await breaks.nth(1).boundingBox()
  expect(firstBreak!.y).toBeGreaterThan(top!.y + top!.height)
  expect(firstBreak!.y + firstBreak!.height).toBeLessThan(middle!.y)
  expect(secondBreak!.y).toBeGreaterThan(middle!.y + middle!.height)
  expect(secondBreak!.y + secondBreak!.height).toBeLessThan(low!.y)
  await page.locator('.physics-panel').screenshot({ path: 'test-results/energy-ladder-superposition.png' })
  await secondary.fill('8'); await secondary.press('Enter')
  await expect(stage).toHaveAttribute('data-displayed-j2', '8')
  await expect(ladder.locator('.ladder > div > span')).toHaveText(['J = 8', 'J = 3', 'J = 2', 'J = 1', 'J = 0'])
  await expect(ladder.locator('.ladder > div.current')).toHaveCount(1)
  await expect(ladder.getByLabel('Energy scale break')).toHaveCount(1)
  await page.getByRole('button', { name: 'Superposition mode', exact: true }).click()
  await expect(stage).toHaveAttribute('data-superposition', 'false')
  await expect(ladder.getByLabel('Energy scale break')).toHaveCount(1)
})
