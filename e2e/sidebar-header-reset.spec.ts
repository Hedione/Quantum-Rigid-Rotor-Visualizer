import { expect, test } from '@playwright/test'

test('sidebar settings stay accessible and header information works on desktop and mobile', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.locator('[aria-busy]')).toHaveAttribute('aria-busy', 'false')
  await page.getByRole('button', { name: 'Pause sampling', exact: true }).click()
  await page.evaluate(() => scrollTo(0, 0))
  const sidebar = page.getByRole('complementary', { name: 'Simulation controls' })
  const controls = await sidebar.boundingBox()
  const stage = await page.getByRole('region', { name: 'Unified classical and quantum rotor experiment' }).boundingBox()
  expect(controls!.x + controls!.width).toBeLessThan(stage!.x)
  expect(Math.abs(controls!.y - stage!.y)).toBeLessThan(2)
  expect((await page.getByRole('spinbutton', { name: 'J', exact: true }).boundingBox())!.y).toBeLessThan(300)
  const quantum = page.getByRole('region', { name: 'Quantum state', exact: true })
  await expect(quantum.getByRole('button', { name: 'Superposition mode', exact: true })).toBeVisible()
  await expect(sidebar.getByRole('heading', { name: 'Superposition mode', exact: true })).toHaveCount(0)
  await expect(sidebar.locator('.section-number')).toHaveText(['01', '02', '03'])
  const bond = await page.getByRole('slider', { name: 'Bond length', exact: true }).boundingBox()
  const asymmetric = page.getByRole('button', { name: 'Asymmetric bond', exact: true })
  expect((await asymmetric.boundingBox())!.y).toBeGreaterThan(bond!.y + bond!.height)
  await expect(page.getByRole('spinbutton', { name: 'Particle mass exact value', exact: true })).toBeVisible()
  await asymmetric.click()
  await expect(page.getByRole('spinbutton', { name: 'Particle 1 mass exact value', exact: true })).toBeVisible()
  await expect(page.getByRole('spinbutton', { name: 'Particle 2 mass exact value', exact: true })).toBeVisible()
  await asymmetric.click()
  await expect(page.getByRole('spinbutton', { name: 'Particle mass exact value', exact: true })).toBeVisible()
  const frequency = await page.getByRole('slider', { name: 'Sampling frequency', exact: true }).locator('..').boundingBox()
  const radius = await page.getByRole('slider', { name: 'Atom radius (visualization only)', exact: true }).locator('..').boundingBox()
  expect(Math.abs(frequency!.y - radius!.y)).toBeLessThan(2)
  expect(radius!.x).toBeGreaterThan(frequency!.x)
  const color = await page.getByRole('button', { name: 'Single mint', exact: true }).boundingBox()
  const playback = await page.getByRole('button', { name: 'Resume sampling', exact: true }).boundingBox()
  expect(Math.abs(color!.y + color!.height / 2 - playback!.y - playback!.height / 2)).toBeLessThan(2)
  await expect(page.locator('.explanation-strip')).toHaveCount(0)
  await expect(page.getByText(/Polar angles stay fixed|Independent Monte Carlo samples|Same energy, different descriptions|Increase J with/)).toHaveCount(0)
  const info = page.getByRole('button', { name: 'About this simulation', exact: true })
  const reset = page.getByRole('button', { name: 'RESET SIMULATION', exact: true })
  const infoBox = await info.boundingBox(), resetBox = await reset.boundingBox()
  expect(resetBox!.x).toBeGreaterThan(infoBox!.x + infoBox!.width)
  expect(infoBox!.width).toBe(infoBox!.height)
  await expect(info).toHaveAttribute('aria-expanded', 'false')
  const zAxis = page.getByRole('button', { name: 'z axis', exact: true })
  await expect(zAxis).toHaveAttribute('aria-pressed', 'true')
  await expect(zAxis.locator('.toggle-state')).toHaveText('ON')
  await zAxis.click()
  await page.mouse.move(0, 0)
  await expect(zAxis).toBeEnabled()
  await expect(zAxis).toHaveAttribute('aria-pressed', 'false')
  await expect(zAxis.locator('.toggle-state')).toHaveText('OFF')
  await expect(zAxis).toHaveCSS('background-color', 'rgb(16, 25, 30)')
  await expect(zAxis).toHaveCSS('color', 'rgb(101, 114, 122)')
  await zAxis.focus(); await zAxis.press('Space')
  await expect(zAxis).toHaveAttribute('aria-pressed', 'true')
  await expect(zAxis).toHaveCSS('color', 'rgb(158, 234, 240)')
  await zAxis.press('Enter')
  await expect(zAxis).toHaveAttribute('aria-pressed', 'false')
  await zAxis.press('Space')
  await sidebar.evaluate(element => { element.scrollTop = 0 })
  await page.evaluate(() => scrollTo(0, 0))
  await page.screenshot({ path: 'test-results/sidebar-header-desktop.png', fullPage: true })
  await page.evaluate(() => scrollTo(0, 700))
  expect(await page.evaluate(() => scrollY)).toBeGreaterThan(500)
  expect((await page.getByRole('spinbutton', { name: 'J', exact: true }).boundingBox())!.y).toBeLessThan(300)
  await info.click()
  const dialog = page.getByRole('dialog', { name: 'A laboratory for molecular rotation' })
  await expect(dialog).toBeVisible()
  await expect(info).toHaveAttribute('aria-expanded', 'true')
  await expect(dialog.getByRole('heading', { name: 'Probability ensemble', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await expect(info).toHaveAttribute('aria-expanded', 'false')
  await expect(info).toBeFocused()
  for (const width of [1101, 1100, 761, 760, 540, 390, 320]) {
    await page.setViewportSize({ width, height: 844 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
    await expect(info).toBeVisible()
    await expect(reset).toBeVisible()
    await expect(page.locator('.site-header')).toHaveCSS('height', '74px')
    await expect(page.locator('.brand-title')).toHaveCSS('font-size', '18px')
    await expect(info).toHaveCSS('width', '27px')
    await expect(info).toHaveCSS('height', '27px')
    await expect(reset).toHaveCSS('height', '36px')
    await expect(reset).toHaveCSS('font-size', width <= 720 ? '6px' : '7px')
  }
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(sidebar).not.toBeVisible()
  const settings = page.getByRole('button', { name: 'SIMULATION SETTINGS', exact: true })
  await settings.click()
  await expect(sidebar).toBeVisible()
  await expect(page.getByRole('spinbutton', { name: 'J', exact: true })).toBeVisible()
  await settings.click()
  await expect(sidebar).not.toBeVisible()
  await page.evaluate(() => scrollTo(0, 0))
  await page.screenshot({ path: 'test-results/sidebar-header-mobile.png', fullPage: true })
  await info.click()
  await expect(dialog).toBeVisible()
  await dialog.screenshot({ path: 'test-results/simulation-information-mobile.png' })
  await page.getByRole('button', { name: 'Close information', exact: true }).click()
  await expect(info).toHaveAttribute('aria-expanded', 'false')
  await expect(info).toBeFocused()
  await expect(page.locator('.katex-error')).toHaveCount(0)
  expect(errors).toEqual([])
})

test('reset restores startup settings, clocks, samples, camera views, and chart choices', async ({ page }) => {
  await page.addInitScript(() => {
    const clock = window as typeof window & { resetTestTime: number }
    clock.resetTestTime = 10000
    performance.now = () => clock.resetTestTime
    const raf = requestAnimationFrame.bind(window)
    window.requestAnimationFrame = callback => raf(() => callback(clock.resetTestTime))
  })
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  let workers = 0
  page.on('worker', () => workers++)
  await page.goto('/')
  const stage = page.locator('[aria-busy]')
  await expect(stage).toHaveAttribute('aria-busy', 'false')
  await page.getByRole('button', { name: 'Pause sampling', exact: true }).click()
  const classical = page.getByTestId('scene-classical').locator('canvas')
  const surface = page.getByTestId('scene-wavefunction').locator('canvas')
  const initialClassical = await classical.screenshot()
  const initialSurface = await surface.screenshot()
  const enter = async (name: string, value: string) => {
    const input = page.getByRole('spinbutton', { name, exact: true })
    await input.fill(value); await input.press('Enter')
  }
  await enter('J', '3')
  await page.getByRole('button', { name: 'Superposition mode', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Evolve in time', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Carbon monoxide', exact: true }).click()
  await enter('Number of Classical Rotors exact value', '17')
  for (const name of ['Playback speed', 'Sampling frequency', 'Histogram sampling rate']) {
    const slider = page.getByRole('slider', { name, exact: true })
    await slider.focus(); await slider.press('Home')
  }
  await page.getByRole('button', { name: 'Particle occlusion', exact: true }).click()
  await page.getByRole('button', { name: 'Cyan / coral', exact: true }).click()
  await page.getByRole('button', { name: 'Real component', exact: true }).click()
  await page.getByRole('button', { name: 'Solid-angle probability', exact: true }).click()
  await page.getByRole('button', { name: 'Current batch', exact: true }).click()
  const bins = page.getByRole('slider', { name: 'Histogram bins', exact: true })
  await bins.focus(); await bins.press('End')
  await expect(stage).toHaveAttribute('aria-busy', 'false')
  await page.getByRole('button', { name: 'Resume sampling', exact: true }).click()
  await page.evaluate(() => { (window as typeof window & { resetTestTime: number }).resetTestTime += 1000 })
  await expect.poll(async () => Number(await page.getByTestId('quantum-time').getAttribute('data-time'))).toBeGreaterThan(0)
  await page.getByRole('button', { name: 'Pause sampling', exact: true }).click()
  await surface.scrollIntoViewIfNeeded()
  const view = await surface.boundingBox()
  await page.mouse.move(view!.x + view!.width / 2, view!.y + view!.height / 2)
  await page.mouse.down(); await page.mouse.move(view!.x + view!.width / 2 + 40, view!.y + view!.height / 2 + 20, { steps: 6 }); await page.mouse.up()
  const reset = page.getByRole('button', { name: 'RESET SIMULATION', exact: true })
  await reset.click()
  await expect(reset).toBeFocused()
  await expect(stage).toHaveAttribute('aria-busy', 'false')
  await expect(stage).toHaveAttribute('data-displayed-j', '1')
  await expect(stage).toHaveAttribute('data-evolving', 'false')
  await expect(page.getByRole('spinbutton', { name: 'J', exact: true })).toHaveValue('1')
  await expect(page.getByRole('spinbutton', { name: 'mJ', exact: true })).toHaveValue('0')
  await expect(page.getByTestId('superposition-controls')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Hydrogen', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('slider', { name: 'Playback speed', exact: true })).toHaveAttribute('aria-valuenow', '1')
  await expect(page.getByRole('slider', { name: 'Sampling frequency', exact: true })).toHaveValue('30')
  await expect(page.getByRole('slider', { name: 'Histogram sampling rate', exact: true })).toHaveValue('10')
  await expect(page.getByRole('slider', { name: 'Rotor opacity', exact: true })).toHaveAttribute('aria-valuenow', '0.01')
  await expect(page.getByRole('button', { name: 'Particle occlusion', exact: true })).toHaveAttribute('aria-pressed', 'false')
  await expect(page.getByTestId('scene-ensemble')).toHaveAttribute('data-rotor-count', '2500')
  await expect(page.getByTestId('scene-ensemble')).toHaveAttribute('data-rotor-palette', 'greenViolet')
  await expect(page.getByRole('button', { name: 'Joint angular probability distribution', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('button', { name: 'Density vs cos θ', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(bins).toHaveAttribute('aria-valuenow', '40')
  await expect(page.getByRole('button', { name: 'Current batch', exact: true })).toHaveAttribute('aria-pressed', 'false')
  await expect(page.getByTestId('cumulative-samples')).toHaveText('2,500')
  await expect(page.getByRole('button', { name: 'Pause sampling', exact: true })).toBeVisible()
  expect((await classical.screenshot()).equals(initialClassical)).toBe(true)
  expect((await surface.screenshot()).equals(initialSurface)).toBe(true)
  await page.getByRole('button', { name: 'Superposition mode', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Evolve in time', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('slider', { name: 'Evolution playback speed', exact: true })).toHaveAttribute('aria-valuenow', '1')
  expect(workers).toBe(1)
  expect(errors).toEqual([])
})
