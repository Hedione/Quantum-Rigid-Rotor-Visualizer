test('unified production experiment, logarithmic controls, and energy-matched motion', async ({ page }) => {
  const failures: string[] = []
  page.on('pageerror', error => failures.push(error.stack ?? error.message))
  await page.goto('/')
  await expect(page.getByRole('region', { name: 'Unified classical and quantum rotor experiment' })).toHaveAttribute('aria-busy', 'false')
  await expect(page.getByRole('region', { name: 'Unified classical and quantum rotor experiment' })).toBeVisible()
  await expect(page.locator('.intro')).toHaveCount(0)
  await expect(page.locator('.stage-caption')).toHaveCount(0)
  await expect(page.getByText('Calculated locally. No data leaves your browser.', { exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'z axis', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Wavefunction', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('heading', { name: 'Wavefunction & probability', exact: true })).toBeVisible()
  await expect(page.getByTestId('pane-wavefunction').locator('.pane-label > span')).toHaveText('WAVEFUNCTION & PROBABILITY')
  await expect(page.getByRole('region', { name: 'Quantum state', exact: true }).locator('summary')).toHaveCount(0)
  await page.getByRole('heading', { name: 'Quantum state', exact: true }).click()
  await expect(page.getByRole('spinbutton', { name: 'J', exact: true })).toBeVisible()
  await expect(page.locator('.state-steppers').first().locator('.stepper label sub')).toHaveText('J')
  for (const name of ['J', 'mJ']) {
    const input = await page.getByRole('spinbutton', { name, exact: true }).boundingBox()
    const slider = await page.getByRole('slider', { name, exact: true }).boundingBox()
    expect(slider!.y).toBeGreaterThan(input!.y + input!.height)
  }
  for (const text of ['A CLOSER LOOK', 'ENERGY-MATCHED CLASSICAL ROTOR', 'Molecular parameters', 'The same energy. Three connected views.']) await expect(page.getByText(text, { exact: true })).toHaveCount(0)
  const stage = await page.getByRole('region', { name: 'Unified classical and quantum rotor experiment' }).boundingBox()
  expect(stage!.y).toBeLessThan(120)
  expect(stage!.height).toBeGreaterThanOrEqual(660)
  await expect(page.locator('canvas')).toHaveCount(3)
  for (const kind of ['classical', 'ensemble', 'wavefunction']) await expect(page.getByTestId(`scene-${kind}`)).toBeVisible()
  await expect(page.getByRole('tab')).toHaveCount(0)
  await expect(page.getByText('3D rendering is unavailable')).toHaveCount(0)
  const classical = await page.getByTestId('pane-classical').boundingBox()
  const ensemble = await page.getByTestId('pane-ensemble').boundingBox()
  const wavefunction = await page.getByTestId('pane-wavefunction').boundingBox()
  expect(Math.abs(classical!.x + classical!.width - ensemble!.x)).toBeLessThanOrEqual(1)
  expect(Math.abs(ensemble!.x + ensemble!.width - wavefunction!.x)).toBeLessThanOrEqual(1)
  expect(ensemble!.width).toBeGreaterThan(classical!.width * 2)
  expect(ensemble!.width * ensemble!.height).toBeGreaterThan(classical!.width * classical!.height * 2)

  await expect(page.getByRole('spinbutton', { name: 'Number of Classical Rotors exact value' })).toHaveCount(0)
  const countSlider = page.getByRole('slider', { name: 'Number of Classical Rotors', exact: true })
  const opacity = page.getByRole('slider', { name: 'Rotor opacity', exact: true })
  await expect(countSlider).toHaveAttribute('aria-valuenow', '5000')
  await expect(countSlider).toHaveAttribute('data-scale', 'logarithmic')
  await expect(opacity).toHaveAttribute('aria-valuetext', '1%')
  await expect(page.getByRole('slider', { name: 'Sampling frequency', exact: true })).toHaveValue('30')
  const playback = page.getByRole('slider', { name: 'Playback speed', exact: true })
  await expect(playback).toHaveAttribute('aria-valuenow', '1')
  await expect(playback).toHaveAttribute('aria-valuetext', '1×')
  await expect(playback).toHaveAttribute('aria-valuemin', '0.01')
  await expect(playback).toHaveAttribute('data-scale', 'logarithmic')
  await expect(page.getByRole('img', { name: /^Polar orientation probability/ })).toBeVisible()
  await expect(page.getByRole('img', { name: /^Azimuthal orientation probability/ })).toBeVisible()
  await page.screenshot({ path: 'test-results/unified-desktop.png', fullPage: true })
  await playback.focus(); await playback.press('Home')
  await expect(playback).toHaveAttribute('aria-valuenow', '0.01')
  await playback.press('PageUp')
  await expect(playback).toHaveAttribute('aria-valuenow', '0.02')

  await page.getByRole('button', { name: 'Pause sampling', exact: true }).click()
  await countSlider.focus()
  await countSlider.press('Home')
  await expect(countSlider).toHaveAttribute('aria-valuenow', '1')
  await expect(page.getByTestId('scene-ensemble')).toHaveAttribute('data-rotor-count', '1')
  await countSlider.press('End')
  await expect(countSlider).toHaveAttribute('aria-valuenow', '10000')
  await expect(page.getByTestId('scene-ensemble')).toHaveAttribute('data-rotor-count', '10000')
  await setRotorCount(page, 1000)
  await expect(page.getByTestId('scene-ensemble')).toHaveAttribute('data-rotor-count', '1000')
  await setRotorCount(page, 2500)
  await opacity.focus()
  await opacity.press('Home')
  await expect(opacity).toHaveAttribute('aria-valuetext', '0.5%')
  await opacity.press('End')
  await expect(opacity).toHaveAttribute('aria-valuetext', '75%')
  // Restore the requested opacity through its logarithmic position.
  await opacity.evaluate(input => {
    const value = String(Math.round(Math.log(0.01 / 0.005) / Math.log(0.75 / 0.005) * 10000))
    Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value')!.set!.call(input, value)
    input.dispatchEvent(new Event('input', { bubbles: true }))
    input.dispatchEvent(new Event('change', { bubbles: true }))
  })
  await expect(opacity).toHaveAttribute('aria-valuetext', '1%')
  await page.getByRole('button', { name: 'Regenerate once', exact: true }).click()
  await page.getByRole('button', { name: 'Current batch', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Cumulative', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Reset cumulative statistics', exact: true }).click()
  await expect(page.getByTestId('cumulative-samples')).toHaveText('0')
  await page.getByRole('button', { name: 'Regenerate once', exact: true }).click()
  await expect(page.getByTestId('cumulative-samples')).toHaveText('2,500')

  const energy1 = Number(await page.getByTestId('energy-value').getAttribute('data-value'))
  const hydrogenEnergy = 1.054571817e-34 ** 2 / (0.5 * 1.66053906892e-27 * (0.74e-10) ** 2)
  expect(energy1 / hydrogenEnergy).toBeCloseTo(1, 12)
  await page.getByRole('spinbutton', { name: 'J', exact: true }).fill('2')
  await page.getByRole('spinbutton', { name: 'J', exact: true }).press('Enter')
  await expect(page.getByRole('region', { name: 'Unified classical and quantum rotor experiment' })).toHaveAttribute('aria-busy', 'false')
  const energy2 = Number(await page.getByTestId('energy-value').getAttribute('data-value'))
  expect(energy2 / energy1).toBeCloseTo(3, 12)
  await page.getByRole('spinbutton', { name: 'J', exact: true }).fill('0')
  await page.getByRole('spinbutton', { name: 'J', exact: true }).press('Enter')
  await expect(page.getByRole('region', { name: 'Unified classical and quantum rotor experiment' })).toHaveAttribute('aria-busy', 'false')
  await expect(page.getByTestId('energy-value')).toHaveAttribute('data-value', '0')
  await expect(page.getByText('J = 0: no rotation; the angular momentum direction is undefined.', { exact: true })).toBeVisible()
  await page.getByRole('spinbutton', { name: 'J', exact: true }).fill('1')
  await page.getByRole('spinbutton', { name: 'J', exact: true }).press('Enter')
  await expect(page.getByRole('region', { name: 'Unified classical and quantum rotor experiment' })).toHaveAttribute('aria-busy', 'false')
  await page.getByRole('button', { name: 'Resume sampling', exact: true }).click()
  await expect(page.getByRole('button', { name: /Pause rotation|Reset rotation|Resume rotation/ })).toHaveCount(0)
  await expect(page.getByRole('slider', { name: 'Playback speed', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Pause sampling', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Reset camera', exact: true }).click()
  expect(failures).toEqual([])
  await expect(page.locator('.katex-error')).toHaveCount(0)
})

