import { expect, test } from '@playwright/test'
import { build } from 'esbuild'
import { resolve } from 'node:path'

declare global { interface Window { transitionTestTime: number; transitionRequests: number } }

test('coherent GPU coefficients reproduce the complex CPU wavefunction and pure density endpoints', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  const bundle = await build({ entryPoints: [resolve('e2e/fixtures/coherent-transition.ts')], bundle: true, write: false, format: 'iife', platform: 'browser' })
  await page.goto('about:blank'); await page.addScriptTag({ content: bundle.outputFiles[0].text })
  const result = await page.evaluate(() => window.coherentGPU)
  await test.info().attach('coherent-gpu-cases', { body: JSON.stringify(result, null, 2), contentType: 'application/json' })
  expect(errors).toEqual([])
  expect(result.cases).toHaveLength(45)
  for (const sample of result.cases) {
    expect(sample.error, JSON.stringify(sample)).toBeLessThan(0.0001)
    if (sample.endpointError !== undefined) expect(sample.endpointError, JSON.stringify(sample)).toBeLessThan(0.0001)
  }
})

test('π-pulse controls scrub, pause, finish, replay and reject forbidden driving without re-preparation', async ({ page }) => {
  test.setTimeout(120000)
  await page.addInitScript(() => {
    window.transitionTestTime = 10000; window.transitionRequests = 0
    performance.now = () => window.transitionTestTime
    const raf = window.requestAnimationFrame.bind(window)
    window.requestAnimationFrame = callback => raf(() => callback(window.transitionTestTime))
    const NativeWorker = window.Worker
    window.Worker = class extends NativeWorker { postMessage(message: unknown) { window.transitionRequests++; super.postMessage(message) } }
  })
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  const stage = page.getByRole('region', { name: 'Unified classical and quantum rotor experiment' })
  await expect(stage).toHaveAttribute('aria-busy', 'false', { timeout: 20000 })
  const quantum = page.getByRole('region', { name: 'Quantum state', exact: true })
  const switchToTransition = quantum.getByRole('button', { name: 'Switch to Transition mode', exact: true })
  await expect(switchToTransition).toHaveCSS('color', 'rgb(255, 155, 73)')
  await expect(page.getByTestId('coherent-controls')).toHaveCount(0)
  await switchToTransition.click()
  await expect(stage).toHaveAttribute('data-displayed-m', '1')
  await expect(stage).toHaveAttribute('data-displayed-m2', '0')
  await expect(stage).toHaveAttribute('aria-busy', 'false')
  await expect(quantum.getByRole('button', { name: 'Switch to Static mode', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Superposition mode', exact: true })).toHaveCount(0)
  await expect(page.getByRole('slider', { name: 'Evolution playback speed', exact: true })).toHaveCount(0)
  await expect(page.getByTestId('transition-validation')).toContainText('Allowed')
  await expect(page.getByRole('combobox', { name: 'Transition polarization' })).toHaveValue('sigmaMinus')
  const population = page.getByTestId('transition-populations')
  const finalPopulation = page.getByRole('progressbar', { name: 'Final population' })
  await expect(finalPopulation).toHaveAttribute('value', '0')
  const requests = await page.evaluate(() => window.transitionRequests)
  const slider = page.getByRole('slider', { name: 'π-pulse progress' })
  const scrub = async (value: number) => {
    await slider.evaluate((element, value) => {
      Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value')!.set!.call(element, String(value))
      element.dispatchEvent(new Event('input', { bubbles: true }))
    }, value)
    await page.evaluate(() => { window.transitionTestTime += 100 })
  }
  await scrub(50)
  await expect.poll(async () => Number(await finalPopulation.getAttribute('value'))).toBeCloseTo(0.5, 10)
  const surface = page.getByTestId('scene-wavefunction').locator('canvas'), before = await surface.screenshot()
  const phase = page.getByRole('slider', { name: 'Drive phase', exact: true })
  await phase.focus(); await phase.press('End')
  await page.evaluate(() => { window.transitionTestTime += 100 })
  expect((await surface.screenshot()).equals(before)).toBe(false)
  await expect(population).toContainText('Total population: 1.000000')
  await page.getByRole('button', { name: 'Resume transition', exact: true }).click()
  await page.evaluate(() => { window.transitionTestTime += 500 })
  await expect.poll(async () => Number(await population.getAttribute('data-progress'))).toBeGreaterThan(0.5)
  await page.getByRole('button', { name: 'Pause transition', exact: true }).click()
  const frozen = await population.getAttribute('data-time')
  await page.evaluate(() => { window.transitionTestTime += 10000 })
  await expect(population).toHaveAttribute('data-time', frozen!)
  await page.getByRole('button', { name: 'Resume transition', exact: true }).click()
  await page.evaluate(() => { window.transitionTestTime += 100000 })
  await expect(finalPopulation).toHaveAttribute('value', '1')
  await expect(page.getByRole('button', { name: 'Replay transition', exact: true })).toBeEnabled()
  const finalTime = await population.getAttribute('data-time')
  await page.evaluate(() => { window.transitionTestTime += 10000 })
  await expect(population).toHaveAttribute('data-time', finalTime!)
  await page.getByRole('button', { name: 'Replay transition', exact: true }).click()
  await page.evaluate(() => { window.transitionTestTime += 100 })
  await expect.poll(async () => Number(await population.getAttribute('data-progress'))).toBeLessThan(0.1)
  await page.getByRole('button', { name: 'Reset transition', exact: true }).click()
  await page.evaluate(() => { window.transitionTestTime += 100 })
  await expect(finalPopulation).toHaveAttribute('value', '0')
  await page.getByRole('combobox', { name: 'Transition polarization' }).selectOption('pi')
  await page.evaluate(() => { window.transitionTestTime += 100 })
  await expect(page.getByTestId('transition-validation')).toContainText('Forbidden')
  await expect(page.getByRole('button', { name: 'Play transition', exact: true })).toBeDisabled()
  await expect(slider).toBeDisabled()
  expect(await page.evaluate(() => window.transitionRequests)).toBe(requests)
  await page.getByRole('combobox', { name: 'Transition polarization' }).selectOption('sigmaMinus')
  for (const width of [1920, 1100, 760, 390, 320]) {
    await page.setViewportSize({ width, height: 950 })
    if (width <= 760 && await page.getByRole('button', { name: 'SIMULATION SETTINGS', exact: true }).getAttribute('aria-expanded') === 'false') await page.getByRole('button', { name: 'SIMULATION SETTINGS', exact: true }).click()
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
    await expect(page.getByRole('combobox', { name: 'Transition polarization' })).toBeVisible()
    const bounds = await page.getByTestId('coherent-controls').evaluate(element => ({ width: element.clientWidth, scroll: element.scrollWidth }))
    expect(bounds.scroll).toBeLessThanOrEqual(bounds.width)
    const modeSwitch = quantum.getByRole('button', { name: 'Switch to Static mode', exact: true })
    await modeSwitch.scrollIntoViewIfNeeded()
    const title = await quantum.getByRole('heading', { name: 'Quantum state', exact: true }).boundingBox()
    const button = await modeSwitch.boundingBox()
    expect(button!.x).toBeGreaterThanOrEqual(title!.x + title!.width)
    expect(Math.abs(button!.y + button!.height / 2 - title!.y - title!.height / 2)).toBeLessThan(2)
    await expect(modeSwitch).toHaveCSS('color', 'rgb(255, 155, 73)')
  }
  await page.screenshot({ path: 'test-results/coherent-transition-mobile.png', fullPage: true })
  await page.getByRole('button', { name: 'Switch to Static mode', exact: true }).click()
  await expect(quantum.getByRole('button', { name: 'Switch to Transition mode', exact: true })).toBeVisible()
  await expect(page.getByTestId('coherent-controls')).toHaveCount(0)
  await expect(page.getByRole('slider', { name: 'Evolution playback speed', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Superposition mode', exact: true }).click()
  await expect(page.getByTestId('superposition-controls')).toBeVisible()
  await page.getByRole('button', { name: 'Switch to Transition mode', exact: true }).click()
  await page.getByRole('button', { name: 'RESET SIMULATION', exact: true }).click()
  await expect(stage).toHaveAttribute('data-displayed-m', '0')
  await expect(page.locator('#quantum-mode-controls')).toHaveAttribute('data-mode', 'static')
  expect(errors).toEqual([])
})
