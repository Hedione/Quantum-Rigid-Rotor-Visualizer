import { expect, test, type Page } from '@playwright/test'
import { selectMode, setRotorCount } from './controls'

async function enter(page: Page, name: string, value: string) {
  const input = page.getByRole('spinbutton', { name, exact: true })
  await input.fill(value)
  await input.press('Enter')
}

test('mode memory, Bloch amplitudes, duplicate states, and pulse populations share the rotor timeline', async ({ page }) => {
  test.setTimeout(120000)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  const stage = page.locator('[aria-busy]')
  await expect(stage).toHaveAttribute('aria-busy', 'false')
  await setRotorCount(page, 100)
  await page.getByRole('button', { name: 'Pause sampling', exact: true }).click()
  await enter(page, 'J', '3')
  await selectMode(page, 'superposition')
  await expect(page.getByRole('spinbutton', { name: 'J', exact: true })).toHaveValue('3')
  await page.getByRole('tab', { name: 'Bloch sphere', exact: true }).click()
  const state = page.getByTestId('bloch-readouts')
  await expect(state).toHaveAttribute('data-defined', 'true')
  await expect.poll(async () => Number(await state.getAttribute('data-x'))).toBeCloseTo(1, 8)
  await expect(page.locator('canvas')).toHaveCount(3)
  await expect(page.getByTestId('scene-bloch')).toHaveAttribute('data-display-scale', '1')
  const reference = page.getByRole('tab', { name: 'Classical rotors', exact: true })
  await page.getByRole('tab', { name: 'Bloch sphere', exact: true }).press('Home')
  await expect(reference).toBeFocused()
  await expect(reference).toHaveAttribute('aria-selected', 'true')
  await reference.press('ArrowRight')
  await expect(page.getByRole('tab', { name: 'Bloch sphere', exact: true })).toBeFocused()
  await enter(page, 'Second J', '3')
  await enter(page, 'Second mJ', '0')
  await expect(stage).toHaveAttribute('aria-busy', 'false')
  await expect(state).toHaveAttribute('data-defined', 'false')
  await expect(state).toContainText('Choose two different rotational states')
  await enter(page, 'Second J', '2')
  await expect(state).toHaveAttribute('data-defined', 'true')
  await enter(page, 'J', '4')
  await selectMode(page, 'static')
  await expect(page.getByRole('tab', { name: 'Bloch sphere', exact: true })).toHaveCount(0)
  await expect(page.getByRole('spinbutton', { name: 'J', exact: true })).toHaveValue('3')
  await selectMode(page, 'superposition')
  await expect(page.getByRole('spinbutton', { name: 'J', exact: true })).toHaveValue('4')
  await expect(page.getByRole('tab', { name: 'Bloch sphere', exact: true })).toHaveAttribute('aria-selected', 'true')
  await selectMode(page, 'transition')
  await page.getByRole('button', { name: 'I understand', exact: true }).click()
  await expect(stage).toHaveAttribute('aria-busy', 'false')
  await expect.poll(async () => Number(await state.getAttribute('data-z'))).toBeCloseTo(1, 8)
  const progress = page.getByRole('slider', { name: 'π-pulse progress', exact: true })
  for (const [value, z] of [[50, 0], [100, -1]] as const) {
    await progress.evaluate((element, value) => {
      Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value')!.set!.call(element, String(value))
      element.dispatchEvent(new Event('input', { bubbles: true }))
    }, value)
    await expect.poll(async () => Number(await state.getAttribute('data-z'))).toBeCloseTo(z, 8)
  }
  await page.screenshot({ path: 'test-results/rotor-bloch-desktop.png', fullPage: true })
  await page.getByRole('button', { name: 'RESET SIMULATION', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Simulation mode', exact: true })).toContainText('Static mode')
  await expect(page.getByTestId('scene-bloch')).toHaveCount(0)
  await expect(stage).toHaveAttribute('aria-busy', 'false')
  expect(errors).toEqual([])
})

test('shortcuts respect editors and the information dialog, including Space on focused controls', async ({ page }) => {
  await page.addInitScript(() => { Math.random = () => 0.8 })
  await page.goto('/')
  await expect(page.locator('[aria-busy]')).toHaveAttribute('aria-busy', 'false')
  await setRotorCount(page, 100)
  const randomize = page.getByRole('button', { name: 'Randomize', exact: true })
  await randomize.focus()
  await page.keyboard.press('Space')
  await expect(page.getByRole('button', { name: 'Resume sampling', exact: true })).toBeVisible()
  await expect(page.getByRole('spinbutton', { name: 'J', exact: true })).toHaveValue('1')
  const range = page.getByRole('slider', { name: 'Sampling frequency', exact: true })
  const value = await range.inputValue()
  await range.focus()
  await page.keyboard.press('Space')
  await expect(range).toHaveValue(value)
  await expect(page.getByRole('button', { name: 'Pause sampling', exact: true })).toBeVisible()
  await page.keyboard.press('r')
  await expect(page.getByRole('spinbutton', { name: 'J', exact: true })).toHaveValue('8')
  for (const quantity of ['Probability density', 'Joint angular probability distribution', 'Real component', 'Imaginary component', 'Wavefunction']) {
    await page.keyboard.press('w')
    await expect(page.getByRole('button', { name: quantity, exact: true })).toHaveAttribute('aria-pressed', 'true')
  }
  await enter(page, 'J', '2')
  await page.getByRole('spinbutton', { name: 'J', exact: true }).press('r')
  await expect(page.getByRole('spinbutton', { name: 'J', exact: true })).toHaveValue('2')
  await selectMode(page, 'superposition')
  await page.keyboard.press('/')
  await expect(page.getByRole('tab', { name: 'Bloch sphere', exact: true })).toHaveAttribute('aria-selected', 'true')
  await page.keyboard.press('/')
  await expect(page.getByRole('tab', { name: 'Classical rotors', exact: true })).toHaveAttribute('aria-selected', 'true')
  const info = page.getByRole('button', { name: 'About this simulation', exact: true })
  await info.click()
  const dialog = page.getByRole('dialog')
  const close = dialog.getByRole('button', { name: 'Close information', exact: true })
  const repo = dialog.getByRole('link', { name: 'project on GitHub' })
  await expect(close).toBeFocused()
  await expect(dialog.locator('kbd')).toHaveText(['Space', 'R', 'W', '/'])
  await expect(repo).toHaveAttribute('href', 'https://github.com/Hedione/Quantum-Rigid-Rotor-Visualizer')
  await close.press('Shift+Tab')
  await expect(repo).toBeFocused()
  await repo.press('Tab')
  await expect(close).toBeFocused()
  await page.keyboard.press('r')
  await page.keyboard.press('w')
  await page.keyboard.press('/')
  await dialog.getByRole('heading', { name: 'Keyboard shortcuts' }).click()
  await expect(dialog).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(info).toBeFocused()
  await expect(info).toHaveAttribute('aria-expanded', 'false')
  await expect(page.getByRole('spinbutton', { name: 'J', exact: true })).toHaveValue('2')
  await expect(page.getByRole('button', { name: 'Wavefunction', exact: true })).toHaveAttribute('aria-pressed', 'true')
})

test('mode picker and information styling fit desktop through 320px with reduced motion', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Pause sampling', exact: true }).click()
  await setRotorCount(page, 100)
  for (const width of [1440, 1100, 720, 320]) {
    await page.setViewportSize({ width, height: 1000 })
    await selectMode(page, 'static')
    const trigger = page.getByRole('button', { name: 'Simulation mode', exact: true })
    await trigger.click()
    await expect(trigger).toHaveAttribute('aria-expanded', 'true')
    const options = page.getByRole('group', { name: 'Simulation modes', exact: true }).getByRole('button')
    await expect(options).toHaveCount(3)
    for (const option of await options.all()) await expect(option).toHaveCSS('height', '56px')
    await expect(page.locator('.mode-picker-reveal')).toHaveCSS('transition-duration', '0.18s, 0.18s')
    await trigger.press('Escape')
    await expect(trigger).toBeFocused()
    await expect(trigger).toHaveAttribute('aria-expanded', 'false')
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
    const info = page.getByRole('button', { name: 'About this simulation', exact: true })
    await info.click()
    await expect(page.getByRole('dialog')).toHaveCSS('font-family', 'Manrope, system-ui, sans-serif')
    expect(await page.getByRole('dialog').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
    await page.getByRole('dialog').screenshot({ path: `test-results/rotor-information-${width}.png` })
    await page.keyboard.press('Escape')
    expect(await page.evaluate(() => document.fonts.check('500 12px "DM Mono"') && document.fonts.check('500 24px Manrope'))).toBe(true)
  }
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await selectMode(page, 'superposition')
  await expect(page.locator('.mode-picker-reveal')).toHaveCSS('transition-duration', '0s')
  await expect(page.getByRole('spinbutton', { name: 'Second J', exact: true })).toBeEnabled()
  await page.screenshot({ path: 'test-results/rotor-mode-mobile.png', fullPage: true })
})
