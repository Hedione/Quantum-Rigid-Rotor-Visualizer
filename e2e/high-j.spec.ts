import { expect, test } from '@playwright/test'

test('high-J demonstration narrows toward the classical plane without non-finite rendering', async ({ page }) => {
  // This case includes high-J preparation, six viewport layouts, and a WebGL reset.
  test.setTimeout(120000)
  const failures: string[] = []
  page.on('pageerror', error => failures.push(error.stack ?? error.message))
  await page.goto('/')
  await expect(page.getByRole('region', { name: 'Unified classical and quantum rotor experiment' })).toHaveAttribute('aria-busy', 'false')
  await page.getByRole('button', { name: 'Pause sampling', exact: true }).click()
  for (const [name, value] of [['J', '4'], ['mJ', '-2']]) {
    const input = page.getByRole('spinbutton', { name, exact: true })
    await input.fill(value); await input.press('Enter')
  }
  await page.getByRole('button', { name: 'Enable J > 10', exact: true }).click()
  await expect(page.getByRole('spinbutton', { name: 'J', exact: true })).toHaveValue('50')
  await expect(page.getByRole('spinbutton', { name: 'mJ', exact: true })).toHaveValue('50')
  await expect(page.getByRole('button', { name: 'Follow mJ = J', exact: true })).toHaveCount(0)
  await expect(page.getByRole('region', { name: 'Unified classical and quantum rotor experiment' })).toHaveAttribute('aria-busy', 'false')
  await expect(page.getByRole('region', { name: 'Unified classical and quantum rotor experiment' })).toHaveAttribute('data-displayed-j', '50')
  const jSlider = page.getByRole('slider', { name: 'J', exact: true })
  await expect(jSlider).toHaveAttribute('max', '50')
  await jSlider.focus(); await jSlider.press('ArrowLeft')
  await expect(page.getByRole('spinbutton', { name: 'J', exact: true })).toHaveValue('49')
  await expect(page.getByRole('spinbutton', { name: 'mJ', exact: true })).toHaveValue('49')
  await jSlider.press('End')
  await expect(page.getByRole('spinbutton', { name: 'J', exact: true })).toHaveValue('50')
  await expect(page.getByRole('spinbutton', { name: 'mJ', exact: true })).toHaveValue('49')
  const mSlider = page.getByRole('slider', { name: 'mJ', exact: true })
  await expect(mSlider).toHaveAttribute('max', '50')
  await mSlider.focus(); await mSlider.press('End')
  await expect(page.getByRole('spinbutton', { name: 'mJ', exact: true })).toHaveValue('50')
  await expect(page.getByText('Theory (polar bin average)', { exact: true })).toBeVisible()
  for (const kind of ['classical', 'ensemble', 'wavefunction']) await expect(page.getByTestId(`scene-${kind}`)).toBeVisible()
  await page.getByRole('spinbutton', { name: 'J', exact: true }).fill('200')
  await page.getByRole('spinbutton', { name: 'J', exact: true }).press('Enter')
  await expect(page.getByRole('region', { name: 'Unified classical and quantum rotor experiment' })).toHaveAttribute('aria-busy', 'false')
  await expect(page.getByRole('spinbutton', { name: 'mJ', exact: true })).toHaveValue('50')
  await expect(page.getByRole('region', { name: 'Unified classical and quantum rotor experiment' })).toHaveAttribute('data-displayed-m', '50')
  await expect(page.locator('.ladder > div').first()).toContainText('J = 50')
  await expect(page.locator('.ladder > div').last()).toContainText('J = 0')
  await page.getByRole('button', { name: 'Regenerate once', exact: true }).click()
  await page.screenshot({ path: 'test-results/high-j-classical-limit.png', fullPage: true })
  await mSlider.focus(); await mSlider.press('Home')
  await expect(page.getByRole('spinbutton', { name: 'mJ', exact: true })).toHaveValue('-50')
  await page.getByRole('spinbutton', { name: 'mJ', exact: true }).fill('0')
  await page.getByRole('spinbutton', { name: 'mJ', exact: true }).press('Enter')
  await expect(page.getByRole('region', { name: 'Unified classical and quantum rotor experiment' })).toHaveAttribute('aria-busy', 'false')
  await page.getByRole('spinbutton', { name: 'J', exact: true }).fill('43')
  await page.getByRole('spinbutton', { name: 'J', exact: true }).press('Enter')
  await expect(page.getByRole('region', { name: 'Unified classical and quantum rotor experiment' })).toHaveAttribute('aria-busy', 'false')
  await expect(page.getByRole('region', { name: 'Unified classical and quantum rotor experiment' })).toHaveAttribute('data-displayed-j', '43')
  await expect(page.getByRole('region', { name: 'Unified classical and quantum rotor experiment' })).toHaveAttribute('data-displayed-m', '0')
  await page.getByRole('button', { name: 'Regenerate once', exact: true }).click()
  await page.screenshot({ path: 'test-results/j43-m0-sampling.png', fullPage: true })
  await expect(page.getByText('3D rendering is unavailable')).toHaveCount(0)
  await page.getByRole('button', { name: 'Enable J > 10', exact: true }).click()
  await expect(page.getByRole('spinbutton', { name: 'J', exact: true })).toHaveValue('4')
  await expect(page.getByRole('spinbutton', { name: 'mJ', exact: true })).toHaveValue('-2')
  const stage = page.locator('[aria-busy]')
  await expect(stage).toHaveAttribute('data-displayed-j', '4')
  await expect(stage).toHaveAttribute('data-displayed-m', '-2')
  for (const width of [1440, 1100, 760, 720, 390, 320]) {
    await page.setViewportSize({ width, height: 844 })
    if (width === 760) await page.getByRole('button', { name: 'SIMULATION SETTINGS', exact: true }).click()
    const navigation = page.locator('.state-navigation')
    await navigation.scrollIntoViewIfNeeded()
    const previous = await navigation.getByRole('button', { name: 'Previous', exact: true }).boundingBox()
    const highJ = await navigation.getByRole('button', { name: 'Enable J > 10', exact: true }).boundingBox()
    const next = await navigation.getByRole('button', { name: 'Next', exact: true }).boundingBox()
    const row = await navigation.boundingBox()
    expect(Math.abs(highJ!.x + highJ!.width / 2 - row!.x - row!.width / 2)).toBeLessThan(1)
    const formerWidth = row!.width - previous!.width - next!.width - 10
    expect(highJ!.width / formerWidth).toBeGreaterThan(.42)
    expect(highJ!.width / formerWidth).toBeLessThan(.58)
    expect(previous!.x + previous!.width).toBeLessThanOrEqual(highJ!.x)
    expect(highJ!.x + highJ!.width).toBeLessThanOrEqual(next!.x)
    expect(Math.abs(previous!.y + previous!.height / 2 - highJ!.y - highJ!.height / 2)).toBeLessThan(1)
    expect(await navigation.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
  }
  await page.locator('.state-navigation').screenshot({ path: 'test-results/high-j-navigation-mobile.png' })
  await page.getByRole('button', { name: 'RESET SIMULATION', exact: true }).click()
  await page.getByRole('button', { name: 'SIMULATION SETTINGS', exact: true }).click()
  const highJ = page.getByRole('button', { name: 'Enable J > 10', exact: true })
  await highJ.click(); await highJ.click()
  await expect(page.getByRole('spinbutton', { name: 'J', exact: true })).toHaveValue('1')
  await expect(page.getByRole('spinbutton', { name: 'mJ', exact: true })).toHaveValue('0')
  expect(failures).toEqual([])
  await expect(page.locator('.katex-error')).toHaveCount(0)
})
