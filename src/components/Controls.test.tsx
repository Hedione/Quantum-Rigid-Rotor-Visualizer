// @vitest-environment jsdom
import { afterEach, describe, expect, it, vi } from 'vitest'
import { cleanup, fireEvent, render, screen, within } from '@testing-library/react'
import { useState } from 'react'
import { Controls, type UpdateSettings } from './Controls'
import { defaultSettings } from '../types'
import { ClassicalControls, EnsembleControls, WavefunctionControls } from './SceneControls'
import { Stepper } from './UI'

afterEach(() => { cleanup(); vi.restoreAllMocks() })
function enterQuantum(name: string, value: string) {
  const input = screen.getByRole('spinbutton', { name })
  fireEvent.change(input, { target: { value } }); fireEvent.keyDown(input, { key: 'Enter' })
}
function Harness() {
  const [settings, setSettings] = useState(defaultSettings)
  const update: UpdateSettings = (key, value) => setSettings(p => ({ ...p, [key]: value }))
  return <><Controls settings={settings} update={update} setState={(j, m) => setSettings(p => ({ ...p, j, m }))} /><ClassicalControls settings={settings} update={update} /><EnsembleControls settings={settings} update={update} /><WavefunctionControls settings={settings} update={update} /><output data-testid="state">{settings.j},{settings.m},{settings.count}</output></>
}

describe('control bindings', () => {
  it('does not replace a focused field before its selected text can be overwritten', () => {
    const onChange = vi.fn()
    const { rerender } = render(<Stepper label="mJ" value={40} min={-40} max={40} onChange={onChange} />)
    const input = screen.getByRole('spinbutton', { name: 'mJ' })
    fireEvent.focus(input)
    rerender(<Stepper label="mJ" value={43} min={-43} max={43} onChange={onChange} />)
    expect((input as HTMLInputElement).value).toBe('40')
    fireEvent.change(input, { target: { value: '0' } })
    fireEvent.keyDown(input, { key: 'Enter' })
    expect(onChange).toHaveBeenCalledExactlyOnceWith(0)
  })
  it('preserves a typed m when a linked J update arrives, and commits it only once', () => {
    const onChange = vi.fn()
    const { rerender } = render(<Stepper label="mJ" value={40} min={-40} max={40} onChange={onChange} />)
    const input = screen.getByRole('spinbutton', { name: 'mJ' })
    fireEvent.focus(input)
    fireEvent.change(input, { target: { value: '0' } })
    rerender(<Stepper label="mJ" value={43} min={-43} max={43} onChange={onChange} />)
    expect((input as HTMLInputElement).value).toBe('0')
    fireEvent.keyDown(input, { key: 'Enter' }); fireEvent.blur(input)
    expect(onChange).toHaveBeenCalledExactlyOnceWith(0)
    rerender(<Stepper label="mJ" value={0} min={-43} max={43} onChange={onChange} />)
    expect((input as HTMLInputElement).value).toBe('0')
  })
  it('allows direct quantum-number editing, Enter/blur commits, and temporary empty input', () => {
    render(<Harness />)
    const j = screen.getByRole('spinbutton', { name: 'J' })
    expect(j.tagName).toBe('INPUT')
    expect(screen.queryByRole('combobox', { name: 'J' })).toBeNull()
    fireEvent.change(j, { target: { value: '2' } })
    expect(screen.getByTestId('state').textContent).toBe('1,0,2000')
    fireEvent.keyDown(j, { key: 'Enter' })
    expect(screen.getByTestId('state').textContent).toBe('2,0,2000')
    enterQuantum('mJ', '-2')
    fireEvent.change(j, { target: { value: '1' } }); fireEvent.blur(j)
    expect(screen.getByTestId('state').textContent).toBe('1,-1,2000')
    fireEvent.change(j, { target: { value: '' } }); fireEvent.blur(j)
    expect(j.getAttribute('value')).toBe('1')
  })
  it('defaults to 2000 and maps the 1–5000 logarithmic range, with exact integer input and clamping', () => {
    render(<Harness />)
    const slider = screen.getByRole('slider', { name: 'Number of Classical Rotors' })
    expect(slider.getAttribute('aria-valuemin')).toBe('1')
    expect(slider.getAttribute('aria-valuemax')).toBe('5000')
    expect(slider.getAttribute('data-scale')).toBe('logarithmic')
    expect(slider.getAttribute('step')).toBe('1')
    expect(slider.getAttribute('aria-valuenow')).toBe('2000')
    fireEvent.change(slider, { target: { value: '5000' } })
    expect(screen.getByTestId('state').textContent).toBe('1,0,71')
    fireEvent.change(slider, { target: { value: '10000' } })
    expect(screen.getByTestId('state').textContent).toBe('1,0,5000')
    fireEvent.change(screen.getByRole('spinbutton', { name: 'Number of Classical Rotors exact value' }), { target: { value: '1' } })
    expect(screen.getByTestId('state').textContent).toBe('1,0,1')
    fireEvent.change(screen.getByRole('spinbutton', { name: 'Number of Classical Rotors exact value' }), { target: { value: '5678' } })
    expect(screen.getByTestId('state').textContent).toBe('1,0,5000')
    fireEvent.change(screen.getByRole('spinbutton', { name: 'Number of Classical Rotors exact value' }), { target: { value: '3456' } })
    expect(screen.getByTestId('state').textContent).toBe('1,0,3456')
  })
  it('defaults to 5% opacity and 30 Hz, and uses a logarithmic 0.5–75% opacity range', () => {
    render(<Harness />)
    const opacity = screen.getByRole('slider', { name: 'Rotor opacity' })
    expect(opacity.getAttribute('aria-valuemin')).toBe('0.005')
    expect(opacity.getAttribute('aria-valuemax')).toBe('0.75')
    expect(opacity.getAttribute('aria-valuetext')).toBe('5%')
    expect(opacity.getAttribute('data-scale')).toBe('logarithmic')
    expect(screen.getByRole('slider', { name: 'Sampling frequency' }).getAttribute('value')).toBe('30')
    fireEvent.change(opacity, { target: { value: '0' } })
    expect(opacity.getAttribute('aria-valuetext')).toBe('0.5%')
    fireEvent.change(opacity, { target: { value: '10000' } })
    expect(opacity.getAttribute('aria-valuetext')).toBe('75%')
    fireEvent.change(opacity, { target: { value: '5000' } })
    expect(opacity.getAttribute('aria-valuetext')).toBe('6.12%')
  })
  it('constrains m when J decreases and supports negative m', () => {
    render(<Harness />)
    enterQuantum('J', '2')
    const jSlider = screen.getByRole('slider', { name: 'J' })
    const mSlider = screen.getByRole('slider', { name: 'mJ' })
    expect(jSlider.getAttribute('value')).toBe('2')
    expect(mSlider.getAttribute('min')).toBe('-2')
    expect(mSlider.getAttribute('max')).toBe('2')
    fireEvent.change(mSlider, { target: { value: '-2' } })
    expect((screen.getByRole('spinbutton', { name: 'mJ' }) as HTMLInputElement).value).toBe('-2')
    fireEvent.change(jSlider, { target: { value: '1' } })
    expect(screen.getByTestId('state').textContent).toBe('1,-1,2000')
    expect(mSlider.getAttribute('min')).toBe('-1')
    expect(mSlider.getAttribute('max')).toBe('1')
    enterQuantum('J', '0')
    expect(screen.getByTestId('state').textContent).toBe('0,0,2000')
    expect((mSlider as HTMLInputElement).disabled).toBe(true)
    expect(mSlider.getAttribute('style')).not.toContain('NaN')
  })
  it('removes the retired controls and state preset buttons', () => {
    render(<Harness />)
    for (const label of ['Rotation axis indicator', 'Atom motion trail', 'Initial rotational phase', 'Temporal accumulation', 'START WITH A STATE', 'Reference unit sphere', 'Probability surface overlay', 'Random seed', 'Molecular parameters', 'Atomic mass (each)', 'Molecular bond length']) {
      expect(screen.queryByText(label, { exact: true })).toBeNull()
    }
    expect(screen.queryByRole('button', { name: /Isotropic|Equatorial|Quadrupolar/ })).toBeNull()
    expect(screen.queryByRole('button', { name: /^(1|100|2,000|5,000)$/ })).toBeNull()
    expect(screen.queryByText('Calculated locally. No data leaves your browser.')).toBeNull()
  })
  it('keeps all three view controls in their own permanent regions outside the sidebar', () => {
    render(<Harness />)
    expect(defaultSettings.atomMass).toBe(1)
    expect(defaultSettings.bondLength).toBe(0.74)
    const sidebar = within(screen.getByRole('complementary', { name: 'Simulation controls' }))
    const quantumHeading = sidebar.getByRole('heading', { name: 'Quantum state' })
    expect(quantumHeading.closest('details')).toBeNull()
    fireEvent.click(quantumHeading)
    expect(sidebar.getByRole('spinbutton', { name: 'J' })).toBeTruthy()
    expect(sidebar.getByText('Scene settings').closest('details')?.open).toBe(true)
    expect(sidebar.getByText('J', { selector: '.stepper label sub' })).toBeTruthy()
    expect(sidebar.queryByText('Classical motion')).toBeNull()
    expect(sidebar.queryByText('Wavefunction & probability')).toBeNull()
    expect(sidebar.queryByText('Probability ensemble')).toBeNull()
    expect(sidebar.queryByRole('slider', { name: 'Number of Classical Rotors' })).toBeNull()
    const classical = within(screen.getByTestId('controls-classical'))
    const ensemble = within(screen.getByTestId('controls-ensemble'))
    const wavefunction = within(screen.getByTestId('controls-wavefunction'))
    expect(classical.getByText('Playback speed')).toBeTruthy()
    expect(wavefunction.getByText('Radial quantity')).toBeTruthy()
    expect(classical.getByRole('slider', { name: 'Playback speed' })).toBeTruthy()
    const playback = classical.getByRole('slider', { name: 'Playback speed' })
    expect(playback.getAttribute('value')).toBe('1')
    expect(playback.getAttribute('aria-valuetext')).toBe('1×')
    expect(playback.getAttribute('min')).toBe('0.01')
    expect(playback.getAttribute('step')).toBe('0.01')
    fireEvent.change(playback, { target: { value: '0.01' } })
    expect(playback.getAttribute('value')).toBe('0.01')
    expect(ensemble.getByRole('slider', { name: 'Number of Classical Rotors' })).toBeTruthy()
    expect(within(wavefunction.getByRole('group', { name: 'Radial quantity' })).getAllByRole('button')).toHaveLength(5)
    expect(wavefunction.queryByRole('combobox')).toBeNull()
    expect(screen.getByTestId('controls-classical').querySelector('details')).toBeNull()
    expect(screen.getByTestId('controls-ensemble').querySelector('details')).toBeNull()
    expect(screen.getByTestId('controls-wavefunction').querySelector('details')).toBeNull()
    for (const label of ['Surface opacity', 'Visualization time scale', 'Match quantum L and Lz', 'Circular trajectory', 'Angular momentum arrow']) expect(screen.queryByText(label, { exact: true })).toBeNull()
    expect(screen.queryByRole('button', { name: /Pause rotation|Reset rotation|Resume rotation/ })).toBeNull()
  })
  it('opens at J=50, caps typed and slider values, follows stretched states, and returns to the low-J range', () => {
    render(<Harness />)
    fireEvent.click(screen.getByRole('switch', { name: 'Explore high J (up to 50)' }))
    expect(screen.getByTestId('state').textContent).toBe('50,50,2000')
    const follow = screen.getByRole('switch', { name: 'Follow mJ = J' })
    expect(follow.getAttribute('data-state')).toBe('unchecked')
    enterQuantum('mJ', '0'); enterQuantum('J', '49')
    expect(screen.getByTestId('state').textContent).toBe('49,0,2000')
    fireEvent.click(follow)
    expect(screen.getByTestId('state').textContent).toBe('49,49,2000')
    expect(screen.getByRole('slider', { name: 'J' }).getAttribute('max')).toBe('50')
    expect(screen.getByRole('spinbutton', { name: 'J' }).getAttribute('max')).toBe('50')
    expect(screen.getByRole('slider', { name: 'Playback speed' }).getAttribute('value')).toBe('1')
    enterQuantum('J', '200')
    expect(screen.getByTestId('state').textContent).toBe('50,50,2000')
    fireEvent.click(screen.getByRole('button', { name: 'Previous' }))
    expect(screen.getByTestId('state').textContent).toBe('49,49,2000')
    enterQuantum('mJ', '-25')
    expect(screen.getByRole('switch', { name: 'Follow mJ = J' }).getAttribute('data-state')).toBe('unchecked')
    fireEvent.click(screen.getByRole('switch', { name: 'Explore high J (up to 50)' }))
    expect(screen.getByTestId('state').textContent).toBe('10,-10,2000')
  })
  it('starts with superposition off, permits independent second-state edits, and provides stationary examples', () => {
    render(<Harness />)
    const toggle = screen.getByRole('button', { name: 'Enable' })
    expect(toggle.getAttribute('aria-expanded')).toBe('false')
    expect(screen.getByRole('heading', { name: 'Superposition mode' }).closest('details')).toBeNull()
    expect(screen.queryByRole('switch', { name: 'Superposition mode' })).toBeNull()
    expect(screen.queryByRole('spinbutton', { name: 'Second J' })).toBeNull()
    fireEvent.click(toggle)
    expect(screen.getByRole('button', { name: 'Disable' }).getAttribute('aria-expanded')).toBe('true')
    expect(screen.getByTestId('state').textContent).toBe('1,0,2000')
    enterQuantum('Second J', '3'); enterQuantum('Second mJ', '-3')
    enterQuantum('J', '2')
    expect((screen.getByRole('spinbutton', { name: 'Second J' }) as HTMLInputElement).value).toBe('3')
    expect((screen.getByRole('spinbutton', { name: 'Second mJ' }) as HTMLInputElement).value).toBe('-3')
    enterQuantum('Second J', '1')
    expect((screen.getByRole('spinbutton', { name: 'Second mJ' }) as HTMLInputElement).value).toBe('-1')
    fireEvent.click(screen.getByRole('button', { name: /^Four lobes/ }))
    expect(screen.getByTestId('state').textContent).toBe('2,2,2000')
    expect((screen.getByRole('spinbutton', { name: 'Second J' }) as HTMLInputElement).value).toBe('2')
    expect((screen.getByRole('spinbutton', { name: 'Second mJ' }) as HTMLInputElement).value).toBe('-2')
    expect(screen.queryByRole('switch', { name: 'Show nodal structures' })).toBeNull()
    fireEvent.click(toggle)
    expect(screen.getByRole('button', { name: 'Enable' }).getAttribute('aria-expanded')).toBe('false')
    expect(screen.queryByRole('spinbutton', { name: 'Second J' })).toBeNull()
    expect(screen.getByTestId('state').textContent).toBe('2,2,2000')
  })
  it('selects all five surface quantities with exclusive buttons', () => {
    render(<Harness />)
    const group = within(screen.getByRole('group', { name: 'Radial quantity' }))
    expect(screen.getByRole('heading', { name: 'Wavefunction & probability' })).toBeTruthy()
    expect(group.getByRole('button', { name: 'Joint angular probability distribution' }).getAttribute('aria-pressed')).toBe('true')
    for (const button of group.getAllByRole('button')) {
      fireEvent.click(button)
      expect(button.getAttribute('aria-pressed')).toBe('true')
      expect(group.getAllByRole('button').filter(item => item.getAttribute('aria-pressed') === 'true')).toHaveLength(1)
    }
    fireEvent.click(group.getByRole('button', { name: 'Joint angular probability distribution' }))
    expect(group.queryByRole('button', { name: 'Polar probability' })).toBeNull()
    expect(screen.queryByRole('switch', { name: 'Color by complex phase' })).toBeNull()
  })
  it.each([false, true])('randomizes both legal quantum states within the active J limit (high J: %s)', highJ => {
    render(<Harness />)
    fireEvent.click(screen.getByRole('button', { name: 'Enable' }))
    if (highJ) fireEvent.click(screen.getByRole('switch', { name: 'Explore high J (up to 50)' }))
    const maximum = highJ ? 50 : 10
    expect(screen.queryByRole('button', { name: /^Six lobes/ })).toBeNull()
    const randomize = screen.getByRole('button', { name: 'Randomize both states' })
    const random = vi.spyOn(Math, 'random')
      .mockReturnValueOnce(0).mockReturnValueOnce(0.999999)
      .mockReturnValueOnce(0.999999).mockReturnValueOnce(0)
    fireEvent.click(randomize)
    expect(screen.getByTestId('state').textContent).toBe('0,0,2000')
    expect((screen.getByRole('spinbutton', { name: 'Second J' }) as HTMLInputElement).value).toBe(String(maximum))
    expect((screen.getByRole('spinbutton', { name: 'Second mJ' }) as HTMLInputElement).value).toBe(String(-maximum))
    if (highJ) expect(screen.getByRole('switch', { name: 'Follow mJ = J' }).getAttribute('data-state')).toBe('unchecked')
    random.mockReturnValueOnce(0.999999).mockReturnValueOnce(0.999999)
      .mockReturnValueOnce(0).mockReturnValueOnce(0)
    fireEvent.click(randomize)
    expect(screen.getByTestId('state').textContent).toBe(`${maximum},${maximum},2000`)
    expect((screen.getByRole('spinbutton', { name: 'Second J' }) as HTMLInputElement).value).toBe('0')
    expect((screen.getByRole('spinbutton', { name: 'Second mJ' }) as HTMLInputElement).value).toBe('0')
  })
  it('offers playback without manual angular-momentum direction controls', () => {
    render(<Harness />)
    expect(screen.queryByRole('switch', { name: 'Match quantum L and Lz' })).toBeNull()
    expect(screen.getByRole('slider', { name: 'Playback speed' })).toBeTruthy()
    expect(screen.queryByRole('slider', { name: 'L azimuth' })).toBeNull()
    expect(screen.queryByRole('slider', { name: 'L polar angle' })).toBeNull()
  })
  it('offers an independent 0.01–5x evolution speed with a 1x reset and removes the repeated note', () => {
    render(<Harness />)
    fireEvent.click(screen.getByRole('button', { name: 'Enable' }))
    expect(screen.getByTestId('superposition-controls').textContent).not.toContain('Adding amplitudes creates interference')
    expect(screen.queryByRole('slider', { name: 'Evolution playback speed' })).toBeNull()
    fireEvent.click(screen.getByRole('switch', { name: 'Evolve in time' }))
    const speed = screen.getByRole('slider', { name: 'Evolution playback speed' })
    expect(speed.getAttribute('min')).toBe('0.01'); expect(speed.getAttribute('max')).toBe('5')
    expect(speed.getAttribute('value')).toBe('1')
    fireEvent.change(speed, { target: { value: '5' } })
    expect(speed.getAttribute('value')).toBe('5')
    expect(screen.getByRole('slider', { name: 'Playback speed' }).getAttribute('value')).toBe('1')
    fireEvent.doubleClick(speed)
    expect(speed.getAttribute('value')).toBe('1')
    expect(screen.getByTestId('superposition-controls').textContent).not.toContain('Adding amplitudes creates interference')
  })
  it('double-click resets logarithmic and linear sliders to exact physical defaults', () => {
    render(<Harness />)
    for (const [label, changed, expected] of [
      ['Number of Classical Rotors', '10000', '2000'],
      ['Rotor opacity', '10000', '0.05'],
      ['Sampling frequency', '1', '30'],
      ['Playback speed', '3', '1'],
    ]) {
      const slider = screen.getByRole('slider', { name: label })
      fireEvent.change(slider, { target: { value: changed } })
      expect(slider.getAttribute('aria-valuenow')).not.toBe(expected)
      fireEvent.doubleClick(slider)
      expect(slider.getAttribute('aria-valuenow')).toBe(expected)
    }
  })
  it('double-click resets both quantum pairs with mode defaults and valid m bounds', () => {
    render(<Harness />)
    fireEvent.click(screen.getByRole('button', { name: 'Enable' }))
    enterQuantum('J', '8'); enterQuantum('mJ', '-8')
    fireEvent.doubleClick(screen.getByRole('slider', { name: 'J' }))
    expect(screen.getByTestId('state').textContent).toBe('1,-1,2000')
    fireEvent.doubleClick(screen.getByRole('slider', { name: 'mJ' }))
    expect(screen.getByTestId('state').textContent).toBe('1,0,2000')
    enterQuantum('Second J', '8'); enterQuantum('Second mJ', '-8')
    fireEvent.doubleClick(screen.getByRole('slider', { name: 'Second J' }))
    expect((screen.getByRole('spinbutton', { name: 'Second J' }) as HTMLInputElement).value).toBe('2')
    expect((screen.getByRole('spinbutton', { name: 'Second mJ' }) as HTMLInputElement).value).toBe('-2')
    fireEvent.doubleClick(screen.getByRole('slider', { name: 'Second mJ' }))
    expect((screen.getByRole('spinbutton', { name: 'Second mJ' }) as HTMLInputElement).value).toBe('1')
    fireEvent.click(screen.getByRole('switch', { name: 'Explore high J (up to 50)' }))
    enterQuantum('J', '7'); enterQuantum('mJ', '-7')
    fireEvent.doubleClick(screen.getByRole('slider', { name: 'mJ' }))
    expect(screen.getByTestId('state').textContent).toBe('7,7,2000')
    fireEvent.doubleClick(screen.getByRole('slider', { name: 'J' }))
    fireEvent.doubleClick(screen.getByRole('slider', { name: 'mJ' }))
    expect(screen.getByTestId('state').textContent).toBe('50,50,2000')
    enterQuantum('J', '0')
    fireEvent.doubleClick(screen.getByRole('slider', { name: 'mJ' }))
    expect(screen.getByTestId('state').textContent).toBe('0,0,2000')
  })
})
