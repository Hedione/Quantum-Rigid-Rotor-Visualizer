function enterQuantum(name: string, value: string) {
  const input = screen.getByRole('spinbutton', { name })
  fireEvent.change(input, { target: { value } }); fireEvent.keyDown(input, { key: 'Enter' })
}
function Harness({ acknowledged = true }: { acknowledged?: boolean }) {
  const [settings, setSettings] = useState(defaultSettings)
  const [transitionAcknowledged, setTransitionAcknowledged] = useState(acknowledged)
  const update: UpdateSettings = (key, value) => setSettings(p => ({ ...p, [key]: value }))
  return <><Controls settings={settings} update={update} setState={(j, m) => setSettings(p => ({ ...p, j, m }))} transitionAcknowledged={transitionAcknowledged} acknowledgeTransition={() => setTransitionAcknowledged(true)} /><ClassicalControls settings={settings} update={update} /><EnsembleControls settings={settings} update={update} /><WavefunctionControls settings={settings} update={update} /><output data-testid="state" data-rabi-frequency={settings.rabiFrequency} data-dipole={settings.dipoleMoment} data-loop={settings.transitionLoop}>{settings.j},{settings.m},{settings.count}</output></>
}

